import {chromium} from 'playwright';
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.dirname(fileURLToPath(import.meta.url));
await fs.mkdir(path.join(root,'capture'),{recursive:true});
const browser=await chromium.launch({channel:'msedge',headless:true});
const context=await browser.newContext({viewport:{width:1600,height:900},deviceScaleFactor:1,colorScheme:'light'});
await context.addInitScript(()=>localStorage.setItem('theme','light'));
const page=await context.newPage();
const errors=[];page.on('pageerror',e=>errors.push(String(e)));
await page.goto(process.env.FILM_URL||'http://localhost:3002/en',{waitUntil:'networkidle'});
await page.screenshot({path:path.join(root,'capture','probe-landing.png')});
console.log(JSON.stringify({url:page.url(),title:await page.title(),text:(await page.locator('body').innerText()).slice(0,14500),errors},null,2));
await browser.close();
